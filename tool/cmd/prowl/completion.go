package main

import (
	"fmt"
	"io"
	"os"
	"sort"
	"strings"
)

const completionHelp = `prowl completion <bash|zsh|fish> — print a shell completion script

The script completes commands, subcommands, the flags each command accepts, and the values of
enumerated flags (--format, --fail-on, …). It is generated from the same table the parser uses.

Examples:
  source <(prowl completion bash)                           # current bash session
  prowl completion zsh > "${fpath[1]}/_prowl"               # zsh, then restart the shell
  prowl completion fish > ~/.config/fish/completions/prowl.fish`

func cmdCompletion(args []string) int {
	_, rest, err := parseCommand("completion", args)
	if err != nil {
		return commandParseError(err)
	}
	if len(rest) != 1 {
		fmt.Fprintln(os.Stderr, "usage: prowl completion <bash|zsh|fish>")
		return 2
	}
	if err := writeCompletion(os.Stdout, rest[0]); err != nil {
		fmt.Fprintln(os.Stderr, err)
		return 2
	}
	return 0
}

func writeCompletion(w io.Writer, shell string) error {
	var script string
	switch shell {
	case "bash":
		script = bashCompletion()
	case "zsh":
		script = zshCompletion()
	case "fish":
		script = fishCompletion()
	default:
		return fmt.Errorf("unsupported shell %q; expected bash, zsh or fish", shell)
	}
	_, err := io.WriteString(w, script)
	return err
}

// completionFlags returns the flag specs a top-level command accepts, including the ones scoped to
// its subcommands ("rules.update"), so `prowl rules --<TAB>` offers them too.
func completionFlags(command string) []flagSpec {
	var out []flagSpec
	for _, flag := range cliFlags {
		ok := flag.applies(command)
		for _, scope := range flag.commands {
			ok = ok || strings.HasPrefix(scope, command+".")
		}
		if ok {
			out = append(out, flag)
		}
	}
	return out
}

// enumValues returns the closed value set of an enumerated flag, or nil.
func enumValues(flag flagSpec) []string {
	if !strings.Contains(flag.value, "|") {
		return nil
	}
	return strings.Split(flag.value, "|")
}

// takesFile reports whether a flag's value is a filesystem path.
func takesFile(flag flagSpec) bool { return flag.value == "FILE" || flag.value == "DIR" }

func longNames(flags []flagSpec) []string {
	var names []string
	for _, flag := range flags {
		for _, name := range flag.names {
			if strings.HasPrefix(name, "--") {
				names = append(names, name)
			}
		}
	}
	sort.Strings(names)
	return names
}

func bashCompletion() string {
	var b strings.Builder
	b.WriteString("# bash completion for prowl — generated by 'prowl completion bash'\n_prowl() {\n" +
		"  local cur prev cmd\n  COMPREPLY=()\n  cur=\"${COMP_WORDS[COMP_CWORD]}\"\n  prev=\"${COMP_WORDS[COMP_CWORD-1]}\"\n  cmd=\"${COMP_WORDS[1]}\"\n" +
		"  if [ \"$COMP_CWORD\" -eq 1 ]; then\n")
	fmt.Fprintf(&b, "    COMPREPLY=($(compgen -W %s -- \"$cur\"))\n    return\n  fi\n", shellQuote(strings.Join(commandNames(), " ")))
	b.WriteString("  case \"$prev\" in\n")
	seen := map[string]bool{}
	for _, flag := range cliFlags {
		values := enumValues(flag)
		if values == nil || seen[flag.names[0]] {
			continue
		}
		seen[flag.names[0]] = true
		fmt.Fprintf(&b, "    %s) COMPREPLY=($(compgen -W %s -- \"$cur\")); return ;;\n", strings.Join(flag.names, "|"), shellQuote(strings.Join(values, " ")))
	}
	b.WriteString("  esac\n  if [[ \"$cur\" == -* ]]; then\n    case \"$cmd\" in\n")
	for _, command := range commandNames() {
		fmt.Fprintf(&b, "      %s) COMPREPLY=($(compgen -W %s -- \"$cur\")) ;;\n", command, shellQuote(strings.Join(longNames(completionFlags(command)), " ")))
	}
	b.WriteString("    esac\n    return\n  fi\n  if [ \"$COMP_CWORD\" -eq 2 ]; then\n    case \"$cmd\" in\n")
	for _, parent := range sortedSubcommandParents() {
		fmt.Fprintf(&b, "      %s) COMPREPLY=($(compgen -W %s -- \"$cur\")); return ;;\n", parent, shellQuote(strings.Join(commandSubcommands[parent], " ")))
	}
	fmt.Fprintf(&b, "      help) COMPREPLY=($(compgen -W %s -- \"$cur\")); return ;;\n", shellQuote(strings.Join(commandNames(), " ")))
	b.WriteString("      completion) COMPREPLY=($(compgen -W 'bash zsh fish' -- \"$cur\")); return ;;\n")
	// No reply falls through to bash's default filename completion (-o default).
	b.WriteString("    esac\n  fi\n}\ncomplete -o default -F _prowl prowl\n")
	return b.String()
}

func zshCompletion() string {
	var b strings.Builder
	b.WriteString("#compdef prowl\n# zsh completion for prowl — generated by 'prowl completion zsh'\n\n_prowl() {\n  local cmd=${words[2]}\n  local -a items\n  if (( CURRENT == 2 )); then\n    items=(\n")
	for _, command := range commands {
		fmt.Fprintf(&b, "      %s\n", shellQuote(command.name+":"+command.summary))
	}
	b.WriteString("    )\n    _describe 'command' items\n    return\n  fi\n  case ${words[CURRENT-1]} in\n")
	seen := map[string]bool{}
	for _, flag := range cliFlags {
		if seen[flag.names[0]] {
			continue
		}
		seen[flag.names[0]] = true
		if values := enumValues(flag); values != nil {
			fmt.Fprintf(&b, "    %s) compadd -- %s; return ;;\n", strings.Join(flag.names, "|"), strings.Join(values, " "))
		} else if takesFile(flag) {
			fmt.Fprintf(&b, "    %s) _files; return ;;\n", strings.Join(flag.names, "|"))
		}
	}
	b.WriteString("  esac\n  if [[ ${words[CURRENT]} == -* ]]; then\n    case $cmd in\n")
	for _, command := range commandNames() {
		fmt.Fprintf(&b, "      %s)\n        items=(\n", command)
		for _, flag := range completionFlags(command) {
			for _, name := range flag.names {
				if strings.HasPrefix(name, "--") {
					// _describe splits on the first unescaped colon, so the description may hold any.
					fmt.Fprintf(&b, "          %s\n", shellQuote(name+":"+flag.description))
				}
			}
		}
		b.WriteString("        ) ;;\n")
	}
	b.WriteString("    esac\n    _describe 'flag' items\n    return\n  fi\n  if (( CURRENT == 3 )); then\n    case $cmd in\n")
	for _, parent := range sortedSubcommandParents() {
		fmt.Fprintf(&b, "      %s) compadd -- %s; return ;;\n", parent, strings.Join(commandSubcommands[parent], " "))
	}
	fmt.Fprintf(&b, "      help) compadd -- %s; return ;;\n", strings.Join(commandNames(), " "))
	b.WriteString("      completion) compadd -- bash zsh fish; return ;;\n    esac\n  fi\n  _files\n}\n\n" +
		"# Works both autoloaded from $fpath and sourced directly.\nif [ \"${funcstack[1]}\" = _prowl ]; then\n  _prowl \"$@\"\nelse\n  compdef _prowl prowl\nfi\n")
	return b.String()
}

func fishCompletion() string {
	var b strings.Builder
	b.WriteString("# fish completion for prowl — generated by 'prowl completion fish'\n")
	for _, command := range commands {
		fmt.Fprintf(&b, "complete -c prowl -n __fish_use_subcommand -f -a %s -d %s\n", command.name, shellQuote(command.summary))
	}
	for _, parent := range sortedSubcommandParents() {
		fmt.Fprintf(&b, "complete -c prowl -n '__fish_seen_subcommand_from %s; and not __fish_seen_subcommand_from %s' -f -a %s\n",
			parent, strings.Join(commandSubcommands[parent], " "), shellQuote(strings.Join(commandSubcommands[parent], " ")))
	}
	b.WriteString("complete -c prowl -n '__fish_seen_subcommand_from completion' -f -a 'bash zsh fish'\n")
	for _, flag := range cliFlags {
		var owners []string
		everywhere := false
		for _, scope := range flag.commands {
			if scope == "*" {
				everywhere = true
				break
			}
			parent, _, _ := strings.Cut(scope, ".")
			if len(owners) == 0 || owners[len(owners)-1] != parent {
				owners = append(owners, parent)
			}
		}
		line := "complete -c prowl"
		if !everywhere {
			line += fmt.Sprintf(" -n '__fish_seen_subcommand_from %s'", strings.Join(owners, " "))
		}
		for _, name := range flag.names {
			if strings.HasPrefix(name, "--") {
				line += " -l " + name[2:]
			} else {
				line += " -s " + name[1:]
			}
		}
		switch values := enumValues(flag); {
		case values != nil:
			line += " -x -a " + shellQuote(strings.Join(values, " "))
		case takesFile(flag):
			line += " -r -F"
		case flag.value != "":
			line += " -x"
		}
		fmt.Fprintf(&b, "%s -d %s\n", line, shellQuote(flag.description))
	}
	return b.String()
}

func sortedSubcommandParents() []string {
	parents := make([]string, 0, len(commandSubcommands))
	for parent := range commandSubcommands {
		parents = append(parents, parent)
	}
	sort.Strings(parents)
	return parents
}

// shellQuote wraps s in single quotes. The form is the same in bash, zsh and fish as long as s
// holds no backslash, which TestCompletionScripts guarantees for every command and flag text.
func shellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}
